// Generates src/styles/sprites.css: the 9-slice pixel frames used by panels, buttons and fields.
//
//   node scripts/build-sprites.mjs      (or: npm run sprites)
//
// Each sprite is an ASCII grid, one character per source pixel. '.' is transparent; the other
// characters are looked up in the sprite's palette. The CSS scales one source pixel to one
// `--px` (border-image-width = slice * --px), so the frames stay crisp at any UI scale.
import {writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const OUTLINE = '#08171d';

const palettes = {
  panel: {O: OUTLINE, H: '#3a7f9c', F: '#123443', S: '#0c2a37'},
  inset: {O: OUTLINE, S: '#050f14', F: '#0b222c', H: '#2a6078'},
  yellow: {O: OUTLINE, H: '#fff59d', Y: '#ffdf00', D: '#e0bf00', S: '#b89a00'},
  green: {O: OUTLINE, H: '#55d98a', Y: '#009c3b', D: '#008534', S: '#006b28'},
  steel: {O: OUTLINE, H: '#4a8aa6', Y: '#1b4a5e', D: '#163e4f', S: '#0f2d3b'},
  blue: {O: OUTLINE, H: '#4c6fd0', Y: '#002776', D: '#001f5e', S: '#00164a'},
  red: {O: OUTLINE, H: '#f08a7d', Y: '#c93c2c', D: '#aa3123', S: '#7f2419'},
};

// 7x7, slice 3.
const PANEL = ['.OOOOO.', 'OHHHHHO', 'OHFFFSO', 'OHFFFSO', 'OHFFFSO', 'OSSSSSO', '.OOOOO.'];
const INSET = ['.OOOOO.', 'OSSSSSO', 'OSFFFFO', 'OSFFFFO', 'OSFFFFO', 'OHHHHHO', '.OOOOO.'];
// 5x6, slice 2: a text field sunk into the surface.
const FIELD = ['.OOO.', 'OSSSO', 'OSFFO', 'OSFFO', 'OHHHO', '.OOO.'];
// 5x7, slice 2 (top/left/right) and 3 (bottom): a block with a 2px side face.
const BUTTON = ['.OOO.', 'OHHHO', 'OHYDO', 'OHYDO', 'OSSSO', 'OSSSO', '.OOO.'];
// Pressed: the face is 1px and the top edge is in shadow; the element also moves down 1px.
const BUTTON_DOWN = ['.OOO.', 'ODDDO', 'ODYYO', 'ODYYO', 'OYYYO', 'OSSSO', '.OOO.'];

const sprites = [
  ['panel', PANEL, palettes.panel],
  ['inset', INSET, palettes.inset],
  ['field', FIELD, palettes.inset],
  ...['yellow', 'green', 'steel', 'blue', 'red'].flatMap(name => [
    [`btn-${name}`, BUTTON, palettes[name]],
    [`btn-${name}-down`, BUTTON_DOWN, palettes[name]],
  ]),
];

function toSvg(grid, palette) {
  const rects = [];
  grid.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let end = x;
      while (end + 1 < row.length && row[end + 1] === ch) end++;
      if (ch !== '.') {
        const color = palette[ch];
        if (!color) throw new Error(`no palette entry for "${ch}"`);
        rects.push(`<rect x='${x}' y='${y}' width='${end - x + 1}' height='1' fill='${color}'/>`);
      }
      x = end + 1;
    }
  });
  const w = grid[0].length;
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' width='${w}' height='${grid.length}' viewBox='0 0 ${w} ${grid.length}' shape-rendering='crispEdges'>${rects.join('')}</svg>`;
  return `url("data:image/svg+xml,${svg.replaceAll('#', '%23').replaceAll('<', '%3C').replaceAll('>', '%3E')}")`;
}

const css = [
  '/* Generated by scripts/build-sprites.mjs. Do not edit by hand. */',
  ':root {',
  ...sprites.map(([name, grid, palette]) => `  --sprite-${name}: ${toSvg(grid, palette)};`),
  '}',
  '',
].join('\n');

writeFileSync(fileURLToPath(new URL('../src/styles/sprites.css', import.meta.url)), css);
console.log(`Wrote ${sprites.length} sprites.`);
